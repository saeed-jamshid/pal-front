    check('catalog cache invalidates; saved money remains exact IRR', publicProduct.price === 1700000 && publicProduct.allowed_grinds.includes('beans'))
    await section('products'); await page.getByRole('button', { name: /^افزودن / }).click()
    dialog = page.getByRole('dialog'); await dialog.locator('form').waitFor()
    for (const [field, value] of Object.entries({ name: 'Duplicate', slug: product.slug, sku: `AD-${nonce}`, price: '10000', stock: '1' })) await dialog.locator(`#admin-field-${field}`).fill(value)
    await dialog.locator('#admin-field-category').selectOption(String(category.id))
    await dialog.getByRole('button', { name: 'ذخیره تغییرات', exact: true }).click()
    await dialog.getByRole('alert').waitFor()
    check('duplicate slug displays inline error', await dialog.locator('#admin-field-slug-error').isVisible())
    check('failed submit focuses error summary', await dialog.getByRole('alert').evaluate((el) => el === document.activeElement))
    page.once('dialog', (d) => d.accept()); await page.keyboard.press('Escape')
    await dialog.waitFor({ state: 'hidden' }); check('Escape closes editor with unsaved-change confirmation')
    await section('images'); await page.getByRole('button', { name: /^افزودن / }).click()
    dialog = page.getByRole('dialog'); await dialog.locator('form').waitFor()
    await dialog.locator('#admin-field-product').selectOption(String(product.id))
    await dialog.locator('#admin-field-image').setInputFiles(path.join(dir, 'receipt.png'))
    await dialog.locator('#admin-field-alt_text').fill('تصویر نمونه قهوه')
    const imageRes = page.waitForResponse((r) => r.url().includes('/manage/images/') && r.request().method() === 'POST')
    await dialog.getByRole('button', { name: 'ذخیره تغییرات', exact: true }).click()
    const imageResponse = await imageRes; assert.equal(imageResponse.status(), 201, await imageResponse.text())
    await dialog.waitFor({ state: 'hidden' }); check('real PNG image upload validated and stored')
    const bundle = await create('products', { name: `باندل تست ${nonce}`, slug: `admin-bundle-${nonce}`, sku: `AB-${nonce}`, category: category.id, price: '2000000', stock: '0' })
    await create('bundles', { bundle_product: bundle.id, included_product: product.id, quantity: '1' })
    check('bundle editor creates real components')
    const event = await create('events', { title: `رویداد مدیریت ${nonce}`, price_rial: '1000000' })
    const slot = await create('slots', { event: event.id, start_time: '10:00', end_time: '11:00', registration_ceiling: '4' })
    check('event and valid capacity slot created through UI')
    const registered = await customerApi('POST', '/events/registrations/', null, { time_slot: String(slot.id), card_id: String(demo.card), payment_receipt: { name: 'receipt.png', mimeType: 'image/png', buffer: receipt } })
    assert.equal(registered.status(), 201, await registered.text())
    const registration = await registered.json()
    await section('registrations'); await page.getByRole('searchbox').fill(event.title)
    let row = page.getByRole('row').filter({ hasText: event.title })
    await row.getByRole('button', { name: /^جزئیات / }).click()
    dialog = page.getByRole('dialog')
    const download = page.waitForEvent('download')
    await dialog.getByRole('button', { name: 'دانلود رسید خصوصی', exact: true }).click()
    await download; check('staff downloads event receipt with JWT, not public URL')
    await dialog.locator('#admin-review-note').fill('رسید تست نیاز به اصلاح دارد')
    page.once('dialog', (d) => d.accept()); await dialog.getByRole('button', { name: 'رد با یادداشت', exact: true }).click()
    await dialog.waitFor({ state: 'hidden' })
    check('staff event rejection runs real locked decision service', (await (await customerApi('GET', `/events/registrations/${registration.registration_token}/`)).json()).status === 'rejected')
    assert.equal((await customerApi('POST', `/events/registrations/${registration.registration_token}/receipt/`, null, { payment_receipt: { name: 'receipt.png', mimeType: 'image/png', buffer: receipt } })).status(), 200)
    await page.getByRole('button', { name: 'بازخوانی فهرست', exact: true }).click()
    await page.locator('.admin-table-loading').waitFor({ state: 'hidden' })
    await row.getByRole('button', { name: /^جزئیات / }).click()
    dialog = page.getByRole('dialog'); await dialog.getByRole('button', { name: 'تأیید', exact: true }).waitFor()
    page.once('dialog', (d) => d.accept()); await dialog.getByRole('button', { name: 'تأیید', exact: true }).click()
    await dialog.waitFor({ state: 'hidden' }); check('staff event approval button confirms replacement receipt')
    const address = await customerApi('POST', '/auth/addresses/', { title: 'Test', recipient_name: 'Test', recipient_phone: demo.phone, province: 'Test', city: 'Test', postal_address: 'Local only', postal_code: '1234567890' })
    assert.equal(address.status(), 201, await address.text())
    assert.equal((await customerApi('POST', '/cart/items/', { product_id: product.id, quantity: 1, grind_type: 'beans' })).status(), 201)
    const checkout = await customerApi('POST', '/orders/checkout/', { address_id: (await address.json()).id, payment_method: 'card_to_card' })
    assert.equal(checkout.status(), 201, await checkout.text()); const order = await checkout.json()
    const paymentRes = await customerApi('POST', `/payments/card/start/${order.order_number}/`, { card_id: demo.card })
    const payment = await paymentRes.json(); assert.ok(payment.payment_id)
    assert.equal((await customerApi('POST', `/payments/card/${payment.payment_id}/receipt/`, null, { receipt: { name: 'receipt.png', mimeType: 'image/png', buffer: receipt } })).status(), 201)
    await section('payments'); await page.getByRole('searchbox').fill(order.order_number)
    row = page.getByRole('row').filter({ hasText: order.order_number }); await row.getByRole('button', { name: /^جزئیات / }).click()
    dialog = page.getByRole('dialog'); page.once('dialog', (d) => d.accept())
    await dialog.getByRole('button', { name: 'تأیید', exact: true }).click(); await dialog.waitFor({ state: 'hidden' })
    check('store receipt approved through frontend', (await (await customerApi('GET', `/orders/${order.order_number}/`)).json()).payment_status === 'paid')
    publicProduct = await (await context.request.get(`${origin}/api/v1/products/${product.slug}/`)).json()
    check('approval commits stock once', publicProduct.available_stock === 2)
    dialog = await edit('orders', order.order_number)
    await dialog.locator('#admin-field-fulfillment_status').selectOption('preparing')
    await dialog.locator('#admin-field-tracking_code').fill('LOCAL-TEST')
    await save(dialog, 'orders'); check('paid order fulfillment and tracking updated through UI')
    check('financial amount still immutable via direct staff request', (await staffApi('PATCH', `/manage/orders/${order.id}/`, { total_amount: 1 })).status() === 400)
    const blogCategory = await create('blog-categories', { name: `موضوع ${nonce}`, slug: `admin-blogcat-${nonce}` })
    const post = await create('posts', { title: `مقاله ${nonce}`, slug: `admin-post-${nonce}`, category: blogCategory.id, excerpt: 'خلاصه تست محلی', content: 'محتوای تست محلی', status: 'published' })
    check('article publishes through UI with staff-owned author', !!post.published_at && post.author_name)
    await create('cards', { label: `DEMO ${nonce}`, card_number: '0000000000000000', account_holder: 'DEMO ONLY', bank_name: 'واریز نکنید', is_active: false })
    check('bank card created inactive, safe by explicit choice')
    const otherProfile = await (await customerApi('GET', '/auth/me/')).json()
    dialog = await edit('customers', otherProfile.full_name, otherProfile.phone_number)
    await dialog.locator('#admin-field-full_name').fill(`مشتری مدیریت ${nonce}`)
    await save(dialog, 'customers')
    check('staff edits customer profile without exposing role controls')
    check('customer cannot elevate privilege through admin API', (await customerApi('PATCH', `/manage/customers/1/`, { is_staff: true })).status() === 403)
    check('OTP and provider secrets absent from histories', !JSON.stringify(await (await staffApi('GET', '/manage/notifications/')).json()).includes('otp:') && !JSON.stringify(await (await staffApi('GET', '/manage/gateways/')).json()).includes('"token"'))
    await section('products'); await page.getByRole('searchbox').fill(product.name)
    await page.getByRole('row').filter({ hasText: product.name }).waitFor(); await shot('products-desktop')
    dialog = await edit('products', product.name); await shot('product-editor-desktop')
    await page.keyboard.press('Escape'); await dialog.waitFor({ state: 'hidden' })
    await page.waitForFunction((label) => document.activeElement?.getAttribute('aria-label') === label, `ویرایش ${product.name}`)
    check('clean dialog Escape restores editor trigger focus')
    await page.goto(`${origin}/admin`); await page.getByRole('heading', { name: /خوش آمدید/ }).waitFor()
    await page.setViewportSize({ width: 375, height: 812 }); await shot('overview-mobile')
    check('mobile overview no horizontal page overflow', await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
    await page.getByRole('button', { name: 'باز کردن منوی مدیریت', exact: true }).focus(); await page.keyboard.press('Enter')
    const mobileNav = page.getByRole('navigation', { name: 'مدیریت پَل در موبایل', exact: true })
    await mobileNav.getByRole('link', { name: 'محصولات', exact: true }).focus(); await page.keyboard.press('Enter')
    await page.waitForURL((url) => url.pathname === '/admin/products', { waitUntil: 'domcontentloaded' })
    await page.locator('.admin-table-loading').waitFor({ state: 'hidden' }); await shot('products-mobile')
    check('keyboard mobile navigation and contained table scroll', await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
    await page.getByRole('button', { name: `ویرایش ${product.name}`, exact: true }).click(); await page.getByRole('dialog').locator('form').waitFor(); await shot('product-editor-mobile')
    check('mobile editor fits viewport', await page.getByRole('dialog').evaluate((el) => el.getBoundingClientRect().width <= innerWidth))
    await page.keyboard.press('Escape')
    await page.setViewportSize({ width: 768, height: 1024 }); await shot('products-tablet')
