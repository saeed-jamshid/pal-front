// Local-only admin acceptance. Reuses existing Playwright; no dependency added.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright-core')
const { execFileSync } = require('node:child_process')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const assert = require('node:assert/strict')
const dir = '/tmp/pal-admin'
const origin = 'http://localhost:3005'
const backend = path.resolve(__dirname, '../../..', 'Pal-Back/docker-compose.yml')
const credentials = JSON.parse(fs.readFileSync(path.join(os.homedir(), '.local/state/pal-coffee/local-admin.json')))
const demo = JSON.parse(fs.readFileSync(path.join(dir, 'demo-private.json')))
const receipt = fs.readFileSync(path.join(dir, 'receipt.png'))
const nonce = Date.now().toString(36)
