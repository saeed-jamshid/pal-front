    const product = await create('products', { name: `قهوه تست ${nonce}`, slug: `admin-coffee-${nonce}`, sku: `AC-${nonce}`, category: category.id, price: '1500000', stock: '3' })
    let dialog = await edit('products', product.name)
    await dialog.locator('[name="allowed_grinds"][value="beans"]').check()
    await dialog.locator('#admin-field-price').fill('1700000')
    await save(dialog, 'products')
    check('product price and allowed grinds edited through UI')
