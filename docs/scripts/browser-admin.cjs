    check('real staff OTP login opens protected overview')
    check('public storefront header hidden only inside admin', await page.locator('body > header').isHidden())
    await shot('overview-desktop')
    const category = await create('categories', { name: `دسته تست ${nonce}`, slug: `admin-cat-${nonce}` })
