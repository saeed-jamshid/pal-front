/* eslint-disable @typescript-eslint/no-require-imports -- standalone browser check */
// Uses existing Playwright; verifies landing animation and light-only theme.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright-core')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const origin = process.env.PAL_ORIGIN || 'http://localhost:3005'
const dir = process.env.PAL_EVIDENCE_DIR || '/tmp/pal-landing'
fs.mkdirSync(dir, { recursive: true })
;(async () => {
  const browser = await chromium.launch({ executablePath: '/usr/bin/chromium', args: ['--no-sandbox', '--proxy-server=direct://'] })
  const checks = [], errors = []
  const check = (name, value) => { assert.ok(value, name); checks.push(name) }
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, colorScheme: 'dark' })
    await context.addInitScript(() => { if (window === window.top) localStorage.setItem('theme', 'dark') })
    const page = await context.newPage()
    page.on('pageerror', e => errors.push(e.message))
    await page.goto(origin)
    await page.waitForFunction(() => document.documentElement.classList.contains('white'))
    check('saved/system dark theme ignored', !await page.evaluate(() => document.documentElement.classList.contains('dark')))
    await page.keyboard.press('d')
    check('dark keyboard shortcut disabled', await page.evaluate(() => document.documentElement.classList.contains('white')))
    const iframe = page.locator('iframe[src="/pal-design/landing-animated.html"]')
    check('artwork sandbox allows scripts only', await iframe.getAttribute('sandbox') === 'allow-scripts')
    const art = page.frameLocator('iframe')
    await art.locator('svg.ready').waitFor()
    check('generated coffee plants present', await art.locator('#plantL .leaf').count() > 0)
    const svg = await iframe.elementHandle()
    const frame = await svg.contentFrame()
    const before = await art.locator('#flagA').getAttribute('d')
    await page.waitForTimeout(200)
    check('flag animates', before !== await art.locator('#flagA').getAttribute('d'))
    await art.getByRole('button', { name: 'توقف حرکت', exact: true }).focus()
    await page.keyboard.press('Enter')
    const paused = await art.locator('#flagA').getAttribute('d')
    await page.waitForTimeout(200)
    check('keyboard pause freezes animation', paused === await art.locator('#flagA').getAttribute('d'))
    await art.getByRole('button', { name: 'ادامهٔ حرکت', exact: true }).click()
    await art.getByRole('button', { name: 'پخش دوبارهٔ تصویر آب‌انبار و قهوهٔ پَل', exact: true }).focus()
    await page.keyboard.press('Enter')
    check('keyboard replay restarts intro', await frame.evaluate(() => document.querySelector('.df').getAnimations()[0].currentTime < 1000))
    await page.waitForTimeout(3200)
    await page.screenshot({ path: `${dir}/landing-desktop.png`, animations: 'disabled' })
    check('store and event links unchanged', await page.getByRole('link', { name: 'خرید قهوه', exact: true }).getAttribute('href') === '/catalog' && await page.getByRole('link', { name: 'رویدادها و ثبت‌نام', exact: true }).getAttribute('href') === '/submit')
    await page.setViewportSize({ width: 1440, height: 400 })
    await page.evaluate(() => scrollTo(0, document.body.scrollHeight))
    await art.locator('svg.paused').waitFor({ state: 'attached' })
    check('offscreen animation paused', await art.locator('svg').getAttribute('class').then(c => c.includes('paused')))
    await page.setViewportSize({ width: 375, height: 812 })
    await iframe.scrollIntoViewIfNeeded()
    await page.waitForTimeout(300)
    check('mobile no page overflow', await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
    await page.screenshot({ path: `${dir}/landing-mobile.png`, animations: 'disabled' })
    await context.close()
    const reduced = await browser.newContext({ viewport: { width: 375, height: 812 }, reducedMotion: 'reduce', colorScheme: 'dark' })
    const reducedPage = await reduced.newPage()
    await reducedPage.goto(origin)
    const reducedArt = reducedPage.frameLocator('iframe')
    await reducedArt.locator('svg.ready').waitFor()
    check('reduced-motion pause control hidden', await reducedArt.locator('#pause').isHidden())
    check('reduced-motion scene has no running animation', await reducedArt.locator('svg').evaluate(el => el.getAnimations({ subtree: true }).filter(a => a.playState === 'running').length === 0))
    check('reduced-motion drawing complete', await reducedArt.locator('.df').first().evaluate(el => parseFloat(getComputedStyle(el).strokeDashoffset) === 0))
    await reducedPage.screenshot({ path: `${dir}/landing-reduced-motion.png`, animations: 'disabled' })
    assert.deepEqual(errors, [], 'no runtime errors')
    check('no runtime errors', true)
    fs.writeFileSync(`${dir}/report.json`, JSON.stringify({ checks, errors, pass: checks.length }, null, 2))
    console.log(`${checks.length} landing checks passed`)
  } finally { await browser.close() }
})().catch(e => { console.error(e); process.exitCode = 1 })
