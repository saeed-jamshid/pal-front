// Run with PLAYWRIGHT_MODULE pointing to existing playwright-core installation.
// Requires isolated seed-demo.py fixtures. Never point this script at production.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright-core')
const { execFileSync } = require('node:child_process')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const assert = require('node:assert/strict')
const origin = 'http://localhost:3005'
const backend = path.resolve(__dirname, '../../..', 'Pal-Back')
const dir = process.env.PAL_EVIDENCE_DIR || '/tmp/pal-integration'
const demo = JSON.parse(fs.readFileSync(path.join(dir, 'demo-private.json'), 'utf8'))
const checks = []
const errors = []
const check = (name, value) => { assert.ok(value, name); checks.push(name) }
const report = path.join(dir, 'browser-report.json')

;(async () => {
  const browser = await chromium.launch({ executablePath: '/usr/bin/chromium', headless: true, args: ['--no-sandbox', '--proxy-server=direct://', '--proxy-bypass-list=*'] })
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } })
  const page = await context.newPage()
  page.on('pageerror', (e) => errors.push(e.message))
  try {
    const products = await (await context.request.get(`${origin}/api/v1/products/`)).json()
    const product = products.results.find((p) => p.available_stock > 2 && p.allowed_grinds.includes('beans'))
    check('proxy GET returns products without redirect loop', !!product)
    await page.goto(`${origin}/catalog/${product.slug}`)
    await page.getByRole('button', { name: 'افزودن به سبد', exact: true }).first().click()
    await page.waitForURL((url) => url.pathname === '/login', { waitUntil: 'domcontentloaded' })
    await page.getByLabel('شماره موبایل', { exact: true }).fill(demo.phone)
    const otpResponse = page.waitForResponse((r) => r.url().includes('/auth/otp/request/'))
    await page.getByLabel('شماره موبایل', { exact: true }).press('Enter')
    check('OTP request accepts phone_number through proxy', (await otpResponse).status() === 202)
    let code
    for (let i = 0; i < 30; i++) {
      const logs = execFileSync('docker', ['compose', '-p', 'pal-local', '-f', path.join(backend, 'docker-compose.yml'), 'logs', '--since', '5m', 'worker'], { encoding: 'utf8' })
      code = [...logs.matchAll(new RegExp(`SMS to ${demo.phone}: .*?([0-9]{6})`, 'g'))].at(-1)?.[1]
      if (code) break
      await page.waitForTimeout(500)
    }
    check('console SMS worker delivers real generated OTP', !!code)
    await page.getByLabel('کد تایید', { exact: true }).fill(code)
    await page.getByLabel('کد تایید', { exact: true }).press('Enter')
    await page.waitForURL(`**/catalog/${product.slug}`)
    check('OTP login restores product destination', page.url().includes(product.slug))
    await page.getByRole('button', { name: 'افزودن به سبد', exact: true }).first().click()
    await page.waitForURL('**/cart')
    await page.getByRole('heading', { name: 'سبد خرید', exact: true }).waitFor()
    await page.getByText(product.name, { exact: true }).first().waitFor()
    check('real cart displays backend product name', true)
    await page.getByRole('button', { name: 'افزایش تعداد', exact: true }).click()
    await page.waitForTimeout(500)
    const names = { recipientName: 'PAL test customer', recipientPhone: demo.phone, province: 'خراسان جنوبی', city: 'بیرجند', postalAddress: 'آدرس تست محلی — ارسال نکنید', postalCode: '1234567890' }
    for (const [name, value] of Object.entries(names)) await page.locator(`[name="${name}"]`).fill(value)
    await page.getByRole('button', { name: 'ذخیره آدرس', exact: true }).click()
    await page.locator('select[name="address"] option').nth(1).waitFor({ state: 'attached' })
    await page.locator('select[name="address"]').selectOption({ index: 1 })
    await page.getByRole('button', { name: 'ثبت سفارش و ادامه پرداخت', exact: true }).click()
    await page.waitForURL('**/orders/*')
    const orderNumber = page.url().split('/').at(-1)
    await page.getByRole('button', { name: 'دریافت اطلاعات پرداخت', exact: true }).click()
    await page.getByText('در انتظار رسید', { exact: true }).waitFor()
    await page.locator('input[name="receipt"]').setInputFiles(path.join(dir, 'receipt.png'))
    await page.getByRole('button', { name: 'ارسال رسید', exact: true }).click()
    await page.getByText('رسید در انتظار بررسی', { exact: true }).waitFor()
    check('address → checkout → private receipt → pending review', true)
    await page.screenshot({ path: path.join(dir, 'order-pending-desktop.png'), fullPage: true, animations: 'disabled' })
    const auth = await page.evaluate(() => localStorage.getItem('pal_access_token'))
    async function api(method, route, body, access = auth) {
      return context.request.fetch(`${origin}/api/v1${route}`, { method, headers: { Authorization: `Bearer ${access}` }, ...(body ? { data: body } : {}) })
    }
    const paymentId = await page.evaluate((key) => Number(localStorage.getItem(key)), `pal_payment_${orderNumber}`)
    let res = await api('POST', `/payments/card/${paymentId}/decision/`, { decision: 'reject', note: 'رسید تست رد شد' }, demo.staff.access)
    check('staff rejects store receipt', res.ok())
    await page.getByRole('button', { name: 'بازخوانی وضعیت', exact: true }).click()
    await page.getByText('رسید رد شده', { exact: true }).waitFor()
    await page.locator('input[name="receipt"]').setInputFiles(path.join(dir, 'receipt.png'))
    await page.getByRole('button', { name: 'ارسال رسید', exact: true }).click()
    await page.getByText('رسید در انتظار بررسی', { exact: true }).waitFor()
    res = await api('POST', `/payments/card/${paymentId}/decision/`, { decision: 'approve' }, demo.staff.access)
    check('staff approves replacement receipt', res.ok())
    const before = (await (await api('GET', `/orders/${orderNumber}/`)).json())
    check('approved store order is paid, still new fulfillment', before.payment_status === 'paid' && before.fulfillment_status === 'new')
    check('repeat payment approval idempotent', (await api('POST', `/payments/card/${paymentId}/decision/`, { decision: 'approve' }, demo.staff.access)).ok())
    check('other user cannot view order', (await api('GET', `/orders/${orderNumber}/`, null, demo.other.access)).status() === 404)
    check('other user cannot download store receipt', (await api('GET', `/payments/card/${paymentId}/receipt/download/`, null, demo.other.access)).status() === 404)
    await page.goto(`${origin}/submit`)
    await page.locator('select').first().selectOption(String(demo.paid_event))
    await page.getByLabel('نام کامل', { exact: true }).fill('مشتری تست پَل')
    await page.locator('[name="time_slot"]').selectOption(String(demo.slot))
    await page.locator('[name="card_id"]').selectOption(String(demo.card))
    await page.locator('[name="payment_receipt"]').setInputFiles(path.join(dir, 'receipt.png'))
    await page.getByRole('button', { name: 'ارسال درخواست ثبت‌نام', exact: true }).click()
    await page.getByRole('heading', { name: 'درخواست ثبت شد', exact: true }).waitFor()
    check('paid event registration uses shared profile + account', true)
    await page.getByRole('link', { name: 'پیگیری ثبت‌نام', exact: true }).click()
    await page.getByText('در انتظار بررسی', { exact: true }).waitFor()
    const token = page.url().split('/').at(-1)
    check('guest cannot access status', (await context.request.get(`${origin}/api/v1/events/registrations/${token}/`)).status() === 401)
    check('other account cannot access event receipt', (await api('GET', `/events/registrations/${token}/receipt/`, null, demo.other.access)).status() === 404)
    check('customer cannot review registration', (await api('POST', `/events/registrations/${token}/decision/`, { decision: 'approve' })).status() === 403)
    check('duplicate registration rejected', (await api('POST', '/events/registrations/', { time_slot: demo.slot })).status() === 400)
    res = await api('POST', `/events/registrations/${token}/decision/`, { decision: 'reject', note: 'لطفاً رسید جدید بفرستید' }, demo.staff.access)
    check('staff rejects event receipt', res.ok())
    await page.reload()
    await page.locator('[name="payment_receipt"]').setInputFiles(path.join(dir, 'receipt.png'))
    await page.getByRole('button', { name: 'ارسال مجدد رسید', exact: true }).click()
    await page.getByText('در انتظار بررسی', { exact: true }).waitFor()
    check('event rejected receipt can resubmit', true)
    check('staff confirms event', (await api('POST', `/events/registrations/${token}/decision/`, { decision: 'approve' }, demo.staff.access)).ok())
    await page.reload()
    await page.getByText('ثبت‌نام شما تأیید شد.', { exact: true }).waitFor()
    await page.goto(`${origin}/submit`)
    await page.locator('select').first().selectOption(String(demo.free_event))
    await page.locator(`select[name="time_slot"] option[value="${demo.full_slot}"]:disabled`).waitFor({ state: 'attached' })
    check('full event slot disabled', true)
    check('backend rejects full slot even with direct request', (await api('POST', '/events/registrations/', { time_slot: demo.full_slot })).status() === 400)
    await page.locator('[name="time_slot"]').selectOption(String(demo.free_slot))
    check('free event needs no receipt', await page.locator('[name="payment_receipt"]').count() === 0)
    await page.getByRole('button', { name: 'ارسال درخواست ثبت‌نام', exact: true }).click()
    await page.getByText(/ثبت‌نام رایگان تأیید شد/).waitFor()
    check('free event auto-confirms', true)
    await page.goto(`${origin}/submit`)
    await page.locator('select').first().selectOption(String(demo.paid_event))
    await page.getByText(/قبلاً ثبت‌نام کرده‌اید/).waitFor()
    check('existing event registration replaces duplicate form', await page.locator('[name="time_slot"]').count() === 0)
    await page.setViewportSize({ width: 390, height: 844 })
    await page.screenshot({ path: path.join(dir, 'events-mobile.png'), fullPage: true, animations: 'disabled' })
    check('events mobile no horizontal overflow', await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
    await page.getByRole('button', { name: 'باز کردن منو', exact: true }).focus()
    await page.keyboard.press('Enter')
    await page.getByRole('navigation', { name: 'ناوبری موبایل', exact: true }).getByRole('link', { name: 'فروشگاه', exact: true }).focus()
    await page.keyboard.press('Enter')
    await page.waitForURL((url) => url.pathname === '/catalog', { waitUntil: 'domcontentloaded' })
    check('mobile menu supports keyboard store navigation', true)
    await page.getByRole('tab', { name: 'همه قهوه‌ها', exact: true }).waitFor()
    await page.getByRole('link').filter({ hasText: product.name }).first().waitFor()
    await page.screenshot({ path: path.join(dir, 'catalog-mobile.png'), fullPage: true, animations: 'disabled' })
    check('catalog mobile no horizontal overflow', await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
    const tool = products.results.find((p) => p.available_stock > 0 && p.allowed_grinds.length === 0)
    if (tool) {
      await page.goto(`${origin}/catalog/${tool.slug}`)
      await page.getByText('این محصول نیازی به آسیاب ندارد.', { exact: true }).waitFor()
      await page.getByRole('button', { name: 'افزودن به سبد', exact: true }).first().click()
      await page.waitForURL((url) => url.pathname === '/cart', { waitUntil: 'domcontentloaded' })
      await page.getByRole('heading', { name: 'سبد خرید', exact: true }).waitFor()
      await page.getByText(tool.name, { exact: true }).first().waitFor()
      check('products without allowed_grinds send empty grind, not beans', true)
      await page.screenshot({ path: path.join(dir, 'cart-mobile.png'), fullPage: true, animations: 'disabled' })
      check('cart mobile no horizontal overflow', await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
    }
    const staffContext = await browser.newContext({ viewport: { width: 1440, height: 1000 } })
    await staffContext.addInitScript((tokens) => { localStorage.setItem('pal_access_token', tokens.access); localStorage.setItem('pal_refresh_token', tokens.refresh) }, demo.staff)
    const staffPage = await staffContext.newPage()
    await staffPage.goto(`${origin}/dashboard`)
    await staffPage.locator('select').selectOption('confirmed')
    await staffPage.getByText(demo.paid_title, { exact: false }).first().waitFor()
    check('staff dashboard uses unified authenticated list', true)
    await staffPage.screenshot({ path: path.join(dir, 'staff-desktop.png'), fullPage: true, animations: 'disabled' })
    await page.goto(`${origin}/dashboard`)
    await page.getByText('این صفحه فقط برای مدیر است.', { exact: true }).waitFor()
    check('customer denied staff dashboard', true)
    const credentials = JSON.parse(fs.readFileSync(path.join(os.homedir(), '.local/state/pal-coffee/local-admin.json'), 'utf8'))
    check('admin credentials target loopback only', credentials.url === 'http://127.0.0.1:8081/admin/')
    const adminPage = await context.newPage()
    await adminPage.goto(credentials.url)
    await adminPage.locator('[name="username"]').fill(credentials.phone_number)
    await adminPage.locator('[name="password"]').fill(credentials.password)
    await adminPage.locator('input[type="submit"]').click()
    await adminPage.locator('#user-tools').waitFor()
    check('Django admin login works with CSRF and isolated local admin', true)
    await adminPage.screenshot({ path: path.join(dir, 'backend-admin.png'), fullPage: true, animations: 'disabled' })
    check('no browser runtime errors', errors.length === 0)
    fs.writeFileSync(report, JSON.stringify({ pass: checks.length, checks, errors }, null, 2))
    console.log(`${checks.length} browser/API checks passed`)
  } catch (error) {
    fs.writeFileSync(report, JSON.stringify({ pass: checks.length, checks, errors, failure: error.message }, null, 2))
    await page.screenshot({ path: path.join(dir, 'failure.png'), fullPage: true }).catch(() => {})
    throw error
  } finally { await browser.close() }
})().catch((e) => { console.error(e.message); process.exitCode = 1 })
